import { createRequire } from 'node:module';
import { readdir, mkdir, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const sharp = require(process.env.SHARP_PATH || 'C:/Users/Admin/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp');
const root = fileURLToPath(new URL('../', import.meta.url));
const source = process.argv[2] || 'C:/Users/Admin/Desktop/作品图片';
const dest = path.join(root, 'assets', 'work');
await mkdir(dest, { recursive: true });
async function walk(dir) {
  const items = await readdir(dir, { withFileTypes: true });
  const output = [];
  for (const item of items) {
    const full = path.join(dir, item.name);
    if (item.isDirectory()) output.push(...await walk(full));
    else if (/\.(png|jpe?g|webp)$/i.test(item.name)) output.push(full);
  }
  return output.sort((a,b)=>a.localeCompare(b,'zh-CN',{numeric:true}));
}
const groups = [
  ['magnetic-keyboard','效果图/键盘/1'], ['mechanical-keyboard','效果图/键盘/2'],
  ['gaming-mouse','效果图/鼠标'], ['campaign-banners','banner'], ['amazon-aplus','亚马逊'],
  ['product-pages','国内平台'], ['campaign-posters','海报'], ['ai-experiments','AI练习'], ['visual-upgrade','视觉优化'],
];
const files = await walk(source);
const manifest = [];
let originalBytes=0, optimizedBytes=0;
for (const [group,prefix] of groups) {
  const selected=files.filter(file=>path.relative(source,file).replaceAll('\\','/').startsWith(prefix+'/'));
  for (let i=0;i<selected.length;i++) {
    const file=selected[i], meta=await sharp(file).metadata();
    const id=`${group}-${String(i+1).padStart(2,'0')}`;
    // WebP has a 16383px dimension limit. Long pages stay full-size JPEGs.
    const ext=meta.height>16000?'.jpg':'.webp';
    const full=path.join(dest,id+ext), thumbnail=path.join(dest,id+'-thumb.webp');
    const optimized=sharp(file).resize({width:Math.min(meta.width,1800),withoutEnlargement:true});
    if(ext==='.jpg') await optimized.jpeg({quality:96,chromaSubsampling:'4:4:4',mozjpeg:true}).toFile(full);
    else await optimized.webp({quality:95,effort:5}).toFile(full);
    const long=meta.height/meta.width>3;
    let thumb=sharp(file);
    if(long) thumb=thumb.extract({left:0,top:0,width:meta.width,height:Math.min(meta.height,Math.round(meta.width*.9))});
    await thumb.resize({width:1000,withoutEnlargement:true}).webp({quality:84,effort:5}).toFile(thumbnail);
    const title=path.basename(file,path.extname(file));
    manifest.push({id,group,title,src:`assets/work/${id}${ext}`,thumbnail:`assets/work/${id}-thumb.webp`,width:meta.width,height:meta.height,previewCropped:long,source:path.relative(source,file).replaceAll('\\','/')});
    originalBytes+=(await stat(file)).size;optimizedBytes+=(await stat(full)).size+(await stat(thumbnail)).size;
  }
}
await writeFile(path.join(root,'artwork.manifest.json'),JSON.stringify(manifest,null,2)+'\n');
await writeFile(path.join(root,'artwork.js'),`// Generated by scripts/prepare-artwork.mjs. Original aspect ratios are retained.\nexport const artwork = ${JSON.stringify(manifest,null,2)};\n`);
console.log(JSON.stringify({images:manifest.length,groups:groups.length,originalMB:(originalBytes/1048576).toFixed(1),webMB:(optimizedBytes/1048576).toFixed(1)}));
